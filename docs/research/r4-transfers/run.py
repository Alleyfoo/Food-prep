"""R4: write the evidence index and the model tables.

    py -3.11 docs/research/r4-transfers/run.py

- `sources.md`: every evidence id (P, K, O, G, B, N, L) in the evidence files,
  with the URL(s) that entry was read from. Built from the files, so an id
  cited in transfers.yaml either resolves here or the test fails.
- `model-tables.md`: every transfer in src/foodprep/data/transfers.yaml run
  through the R3 validator next to its base route.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
sys.path.insert(0, str(ROOT / "src"))

from foodprep import constructions as c  # noqa: E402
from foodprep import transfers as t      # noqa: E402

EVIDENCE = ["evidence-pea-falafel.md", "evidence-kale-onion.md", "evidence-napa.md",
            "evidence-gratin-stems.md", "lidl-pages.md"]
HEAD = re.compile(r"^(?:#{3}\s+|\*\*)([A-Z]\d+)\b(?:\*\*)?\s*[-—.:]*\s*(.*)$")
ROW = re.compile(r"^\|\s*([A-Z]\d+)\s*\|(.*)$")
URL = re.compile(r"https?://[^\s|)>\]]+")


def sources() -> dict:
    """id -> {file, title, urls}"""
    out: dict = {}
    for name in EVIDENCE:
        cur = None
        for line in (HERE / name).read_text(encoding="utf-8").splitlines():
            m = ROW.match(line)
            if m:
                cur = None
                urls = URL.findall(m.group(2))
                if urls and m.group(1) not in out:
                    cells = [x.strip() for x in m.group(2).split("|")]
                    title = next((x for x in cells if x and not URL.search(x)), "")
                    out[m.group(1)] = {"file": name, "title": title, "urls": urls}
                continue
            m = HEAD.match(line)
            if m and m.group(1) not in out:
                cur = m.group(1)
                out[cur] = {"file": name, "title": URL.sub("", m.group(2)).strip(" -—"),
                            "urls": URL.findall(m.group(2))}
                continue
            if line.startswith("#") or line.startswith("**"):
                cur = None
            if cur and not out[cur]["urls"]:
                out[cur]["urls"] = URL.findall(line)
            if cur and not out[cur]["title"] and line.startswith("- ") and not URL.search(line):
                out[cur]["title"] = line[2:].strip()
    return out


def write_sources() -> str:
    src = sources()
    lines = ["# R4 evidence index", "",
             "Generated by `run.py` from the evidence files; do not edit by hand. Each id",
             "names a page that was opened and read on 2026-11-24 (the evidence file says",
             "how: WebFetch returns a model-written summary; the built-in browser and",
             "saved PDFs were read in full; L rows marked *snippet* were seen only as",
             "search snippets). Failed pages are listed in each evidence file and are",
             "never cited.", "",
             "| Id | Source | URL(s) | File |", "| --- | --- | --- | --- |"]
    key = lambda k: (k[0], int(k[1:]))  # noqa: E731
    for sid in sorted(src, key=key):
        s = src[sid]
        title = s["title"].replace("|", "/")[:90]
        lines.append(f"| {sid} | {title} | {' ; '.join(s['urls'])} | `{s['file']}` |")
    return "\n".join(lines) + "\n"


def write_tables() -> str:
    out = ["# R4 model tables", "",
           "Generated by `run.py`: each transfer in `src/foodprep/data/transfers.yaml`,",
           "built from its base route and run through the R3 validator",
           "(`foodprep transfer <id>` prints the same). *holds* = no step, role or",
           "claim fails; the verdict column is the R3 representation verdict (a",
           "recorded model gap makes a route *partly*).", "",
           "| Transfer | Base route (verdict) | Transfer route | Model | Evidence says | Agrees | Verdict |",
           "| --- | --- | --- | --- | --- | --- | --- |"]
    reps = {tid: t.validate(tid) for tid in t.candidate_ids()}
    for tid, rep in reps.items():
        cand = t.load()["candidates"][tid]
        b = cand["base"]
        holds = "-" if rep.model_holds is None else ("holds" if rep.model_holds else "fails")
        agrees = "-" if rep.agrees is None else ("yes" if rep.agrees else "**no**")
        out.append(f"| `{tid}` | {b['dish']}/{b['route']} ({rep.base.verdict}) | "
                   f"{rep.route.verdict if rep.route else '-'} | {holds} | "
                   f"{cand['evidence_says'].replace('_', ' ')} | {agrees} | "
                   f"{cand['verdict'].replace('_', ' ')} |")
    for tid, rep in reps.items():
        r = rep.route
        out += ["", f"## `{tid}`", ""]
        if r is None:
            out.append("Not modelled.")
            continue
        out.append("| Owner | Step | Operation | Status |")
        out.append("| --- | --- | --- | --- |")
        for s in r.steps:
            out.append(f"| {s.owner} | {s.index}{' (alt)' if s.alternative else ''} | "
                       f"{s.op} | {s.status} |")
        out.append("")
        for label, state, v in r.claims:
            out.append(f"- claim {label}: {state} -> {v}")
        for a, step, output, m in r.recombinations:
            out.append(f"- recombination: {a} -> {step} [{output}] -> {m}")
        for f in r.failures:
            out.append(f"- **fails:** {f}")
        for u in r.unknowns:
            out.append(f"- unknown: {u}")
        for g in r.model_gaps:
            out.append(f"- model gap: {g}")
        if rep.evidence_ids:
            out.append(f"- R4 evidence cited in the route: {', '.join(rep.evidence_ids)}")
    return "\n".join(out) + "\n"


def main() -> int:
    (HERE / "sources.md").write_text(write_sources(), encoding="utf-8")
    (HERE / "model-tables.md").write_text(write_tables(), encoding="utf-8")
    print("wrote sources.md and model-tables.md")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
