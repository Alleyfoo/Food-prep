"""R5: write the evidence index, the condition tables and the intermediate states.

    py -3.11 docs/research/r5-processing-conditions/run.py

- `sources.md`: every R5 evidence id (Q) in the evidence files, with the URL
  read. Built from the files, so an id cited in processing_conditions.yaml
  either resolves here or `conditions.errors()` reports it.
- `condition-tables.md`: every pair in src/foodprep/data/processing_conditions.yaml,
  its default and its per-step fields, conflicts and gaps; then every
  documented step that has a condition, route by route.
- `sequence-tables.md`: every recorded sequence (a whole route), member by
  member from raw part to plate, with readiness or doneness per step and each
  member's endpoint after a join.
- `intermediate-tables.md`: each intermediate state, how long it keeps, and the
  documented routes that pass through it with the steps that remain.

Nothing here derives a value: every line is a field of the data file, or the
R1/R3 walk of a documented route.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
sys.path.insert(0, str(ROOT / "src"))

from foodprep import conditions as k   # noqa: E402
from foodprep import constructions as c  # noqa: E402

HEAD = re.compile(r"^### (Q\d+)\s*[—-]+\s*(https?://\S+)\s*$")


def sources() -> dict:
    out: dict = {}
    for path in sorted(HERE.glob("evidence-*.md")):
        cur = None
        for line in path.read_text(encoding="utf-8").splitlines():
            m = HEAD.match(line)
            if m:
                cur = m.group(1)
                out.setdefault(cur, {"file": path.name, "url": m.group(2), "title": ""})
                continue
            if line.startswith("#"):
                cur = None
            elif cur and not out[cur]["title"] and line.startswith("- "):
                out[cur]["title"] = line[2:].strip()
    return out


def write_sources() -> str:
    src = sources()
    lines = ["# R5 evidence index", "",
             "Generated by `run.py` from the evidence files; do not edit by hand. Each Q id",
             "names a page that was opened and read on 2026-11-25; the evidence file says how",
             "(most through WebFetch, a summarising fetch; the spot check in `evaluation.md`",
             "re-read a sample as raw text). Failed and snippet-only pages are listed in each",
             "evidence file and are never cited. R2 ids (E/M/A + letter) resolve to",
             "`../r2-construction-patterns/recipes.md`; R4 ids to `../r4-transfers/sources.md`.",
             "", "| Id | Source | URL | File |", "| --- | --- | --- | --- |"]
    for sid in sorted(src, key=lambda s: int(s[1:])):
        s = src[sid]
        title = s["title"].replace("|", "/")[:90]
        lines.append(f"| {sid} | {title} | {s['url']} | `{s['file']}` |")
    return "\n".join(lines) + "\n"


def _cell(text) -> str:
    return " ".join(str(text).split()).replace("|", "/")


def _fields_rows(f: dict) -> list[str]:
    rows = []
    if f.get("role"):
        rows.append(f"| role | {_cell(f['role'])} |")
    s = f.get("start")
    if s:
        bits = [f"{key}: {', '.join(v) if isinstance(v, list) else v}"
                for key, v in s.items() if key in ("particle", "moisture")]
        rows.append(f"| start | {'; '.join(bits)}{k._src(s)} |")
    for m in f.get("medium") or []:
        bits = [m["medium"].replace("_", " ")]
        if m.get("temp_c"):
            lo, hi = m["temp_c"]
            bits.append(f"{lo}-{hi} C" if lo != hi else f"{lo} C")
        if m.get("cover"):
            bits.append(m["cover"].replace("_", " "))
        if m.get("note"):
            bits.append(_cell(m["note"]))
        rows.append(f"| medium and heat | {'; '.join(bits)}{k._src(m)} |")
    for e in f.get("elapsed") or []:
        rows.append(f"| elapsed | {k._time(e)}{k._src(e)}"
                    + (f" ({_cell(e['note'])})" if e.get("note") else "") + " |")
    a = f.get("active")
    if a:
        rows.append(f"| active work | {a['kind']}{k._src(a)}"
                    + (f" ({_cell(a['note'])})" if a.get("note") else "") + " |")
    for s in f.get("shifts") or []:
        rows.append(f"| time shifts with | {_cell(s['factor'])}: {_cell(s.get('effect', ''))}"
                    f"{k._src(s)} |")
    for ch in f.get("completion") or []:
        rows.append(f"| **done when** | {_cell(ch['check'])}{k._src(ch)} |")
    for ch in f.get("failure") or []:
        cause = f" (cause: {_cell(ch['cause'])})" if ch.get("cause") else ""
        rows.append(f"| **failed if** | {_cell(ch['check'])}{cause}{k._src(ch)} |")
    if f.get("note"):
        rows.append(f"| note | {_cell(f['note'])} |")
    return rows


def _counts(p: dict) -> tuple[int, int, bool, bool]:
    fs = [p.get("default") or {}] + list((p.get("at") or {}).values())
    nc = sum(len(f.get("completion") or []) for f in fs)
    nf = sum(len(f.get("failure") or []) for f in fs)
    el = any(f.get("elapsed") for f in fs)
    ac = any(f.get("active") for f in fs)
    return nc, nf, el, ac


def write_tables() -> str:
    data = k.load()
    out = ["# R5 condition tables", "",
           "Generated by `run.py` from `src/foodprep/data/processing_conditions.yaml`",
           "(`foodprep conditions <pair>` prints the same). A pair's *default* holds only",
           "what its sources agree on; a step's own fields replace the default's at that",
           "step. Conflicting instructions are listed as versions, never averaged. A field",
           "that is absent is unknown: no time or endpoint here is derived from properties.",
           "", "## Summary", "",
           "| Pair | Part | Operation | Steps | Done-when checks | Failed-if checks | "
           "Elapsed | Active | Conflicts | Confidence |",
           "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
    for pid, p in data["pairs"].items():
        nc, nf, el, ac = _counts(p)
        out.append(f"| `{pid}` | {p.get('part')} | {' / '.join(k._ops(p))} | "
                   f"{len(p.get('steps') or [])} | {nc} | {nf} | {'yes' if el else '-'} | "
                   f"{'yes' if ac else '-'} | {len(p.get('conflicts') or [])} | "
                   f"{p.get('confidence')} |")
    for pid, p in data["pairs"].items():
        out += ["", f"## `{pid}`: {p.get('name', '')}", "",
                f"{p.get('part')} -> {' / '.join(k._ops(p))}; confidence "
                f"**{p.get('confidence')}**.", ""]
        if p.get("note"):
            out += [_cell(p["note"]), ""]
        out += ["Default (where the sources agree):", "", "| Field | Value |", "| --- | --- |"]
        out += _fields_rows(p.get("default") or {}) or ["| - | nothing the sources agree on |"]
        for addr in p.get("steps") or []:
            pt = k.resolve_step(addr)
            out += ["", f"At `{addr}`" + (f" (route evidence: {_cell(pt.evidence)})"
                                         if pt and pt.evidence else "") + ":", ""]
            rows = _fields_rows((p.get("at") or {}).get(addr) or {})
            out += (["| Field | Value |", "| --- | --- |"] + rows) if rows else \
                ["the default applies."]
        for cf in p.get("conflicts") or []:
            out += ["", f"Conflict, {_cell(cf['topic'])}:", ""]
            out += [f"- {_cell(v['says'])}{k._src(v)}" for v in cf.get("versions") or []]
            if cf.get("note"):
                out.append(f"- note: {_cell(cf['note'])}")
        if p.get("gaps"):
            out += ["", "Not found:", ""] + [f"- {_cell(g)}" for g in p["gaps"]]
    out += ["", "## Documented routes: the steps with a condition", "",
            "| Route | Step | Operation | Pairs |", "| --- | --- | --- | --- |"]
    for key, r in k.routes().items():
        for pt in r.points:
            pids = k.pairs_for_step(pt.address)
            if pids:
                out.append(f"| {key} | {pt.owner} {pt.index} | {pt.op} | "
                           f"{', '.join(f'`{x}`' for x in pids)} |")
    return "\n".join(out) + "\n"


def _checks(chs) -> str:
    return "; ".join(_cell(ch["check"]) + (f" (cause: {_cell(ch['cause'])})" if ch.get("cause")
                                           else "") + k._src(ch) for ch in chs or [])


def write_sequences() -> str:
    data = k.load()
    out = ["# R5 sequence tables", "",
           "Generated by `run.py`: every recorded sequence is a whole documented route",
           "(`foodprep conditions <route>` prints the same). Each member is followed from",
           "the raw part to the plate: its own steps, then each join it enters and the heat",
           "after it, with *this member's* endpoint there. *readiness* = ready for the next",
           "operation; *doneness* = ready to eat. Times and checks come from the pairs and",
           "the sequence; a blank cell is unknown.", "",
           "| Sequence | Steps | Readiness | Doneness | Member endpoints after a join | "
           "Dependencies | Skip/overdo failures | Alternatives |",
           "| --- | --- | --- | --- | --- | --- | --- | --- |"]
    for key, seq in data["sequences"].items():
        kinds = [s["endpoint"]["kind"] for s in seq["steps"].values()]
        mem = sum(1 for m in (seq.get("members") or {}).values() for x in m.values()
                  if x and (x.get("completion") or x.get("failure")))
        memall = sum(len(m) for m in (seq.get("members") or {}).values())
        out.append(f"| `{key}` | {len(kinds)} | {kinds.count('readiness')} | "
                   f"{kinds.count('doneness')} | {mem} of {memall} | "
                   f"{len(seq.get('depends') or [])} | {len(seq.get('misses') or [])} | "
                   f"{len(seq.get('alternatives') or [])} |")
    for key, seq in data["sequences"].items():
        out += ["", f"## `{key}`: {seq.get('name', '')}", ""]
        for h in k.histories(key):
            out += [f"**{h.member}**, raw to plate:", "",
                    "| Step | Operation | Endpoint | Time | Active | Done when | Failed if |",
                    "| --- | --- | --- | --- | --- | --- | --- |"]
            for p, f, kind, mine in h.lines:
                inside = p.owner != h.member and mine is not None
                done = _checks((mine or {}).get("completion")) if inside else \
                    _checks(f.get("completion"))
                bad = _checks((mine or {}).get("failure")) if inside else _checks(f.get("failure"))
                if inside and not (done or bad) and mine.get("note"):
                    done = f"not found: {_cell(mine['note'])}"
                times = "; ".join(k._time(e) + k._src(e) for e in f.get("elapsed") or [])
                act = (f.get("active") or {}).get("kind", "")
                label = f"{p.owner} {p.index}" + (f" ({h.member} inside)" if inside else "")
                out.append(f"| {label} | {p.op} | {kind or ''} | {times} | {act} | {done} | {bad} |")
            out.append("")
        for d in seq.get("depends") or []:
            out.append(f"- depends: `{d['step']}` exists because of `{d['because']}`: "
                       f"{_cell(d['says'])}{k._src(d)}")
        for m in seq.get("misses") or []:
            out.append(f"- if `{m['step']}` is {m['when']}: {_cell(m['failure'])}{k._src(m)}")
        for f in seq.get("finish") or []:
            times = "; ".join(k._time(e) + k._src(e) for e in f.get("elapsed") or [])
            out.append(f"- then {f['stage']}" + (f": {times}" if times else "")
                       + (f"; done when {_checks(f.get('completion'))}" if f.get("completion")
                          else ""))
        for a in seq.get("alternatives") or []:
            out.append(f"- alternative sequence, {_cell(a.get('name', ''))}"
                       + (f" (`{a['route']}`)" if a.get("route") else "")
                       + f": {_cell(a['says'])}{k._src(a)}")
        for g in seq.get("gaps") or []:
            out.append(f"- evidence stops: {_cell(g)}")
    return "\n".join(out) + "\n"


def write_intermediates() -> str:
    data = k.load()
    out = ["# R5 intermediate states", "",
           "Generated by `run.py`. Each state is a part with R1 operations applied",
           "(`foodprep from <part> <operations...>` prints the same). The routes listed",
           "pass through a state that R1's `Material.key()` calls equivalent, so the",
           "remaining steps are the documented route's own. *food safety* keeping times",
           "come from a public food-safety body; *cooking* ones from cooks or packets.", ""]
    for iid, it in (data.get("intermediates") or {}).items():
        if it.get("at"):
            res = k.from_state(it["at"])
            where = f"the state after step `{it['at']}`"
        else:
            res = k.from_state(it["part"], it.get("after") or [])
            have = " -> ".join(c._en(s.operation) for s in res.state.path) if res.state else "?"
            where = f"{it['part']}: {have}"
        kinds = {m.kind for m in res.matches if m.kind}
        out += [f"## `{iid}`: {it.get('name', '')}", "", f"{where}."
                + (f" Endpoint kind where it is reached: {', '.join(sorted(kinds))}"
                   + (" (not ready to eat)." if kinds == {"readiness"} else ".") if kinds else ""),
                ""]
        if it.get("note"):
            out += [_cell(it["note"]), ""]
        out += ["| Keeps | How | Time | Basis | Sources |", "| --- | --- | --- | --- | --- |"]
        for kp in it.get("keeps") or []:
            out.append(f"| {_cell(kp.get('where', ''))} | {_cell(kp.get('how', ''))} | "
                       f"{k._time(kp) or '-'} | {kp['basis'].replace('_', ' ')} | "
                       f"{', '.join(kp.get('sources') or [])} |")
        if not it.get("keeps"):
            out.append("| - | - | not found | - | - |")
        out += ["", "| Route | From | Remaining steps (with conditions) |", "| --- | --- | --- |"]
        for mt in res.matches:
            steps = []
            for pt in mt.remaining:
                pids = k.pairs_for_step(pt.address)
                steps.append(f"{pt.owner} {pt.index} {pt.op}"
                             + (f" ({', '.join(pids)})" if pids else ""))
            out.append(f"| {mt.route} | {mt.owner} after step {mt.at} | {'; '.join(steps)} |")
        out.append("")
    return "\n".join(out)


def main() -> int:
    (HERE / "sources.md").write_text(write_sources(), encoding="utf-8")
    (HERE / "condition-tables.md").write_text(write_tables(), encoding="utf-8")
    (HERE / "intermediate-tables.md").write_text(write_intermediates(), encoding="utf-8")
    (HERE / "sequence-tables.md").write_text(write_sequences(), encoding="utf-8")
    print("wrote sources.md, condition-tables.md, sequence-tables.md and intermediate-tables.md")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
