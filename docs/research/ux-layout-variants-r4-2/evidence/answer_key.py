"""Answer key for the R4.2 scan and understand tasks, computed from the model.

    PYTHONIOENCODING=utf-8 py -3.11 docs/research/ux-layout-variants-r4-2/evidence/answer_key.py

The facilitator scores a participant's answer against this key: a row
missed (scan) or a meaning misread (understand). Same questions for every
ingredient, so each variant can be shown on a different ingredient.
"""
from __future__ import annotations

import sqlite3
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[4]
sys.path[:0] = [str(ROOT / "docs/research/ux-integrated-r4/prototype"), str(ROOT / "src")]

from foodprep import loader, query  # noqa: E402
import r4_model as M  # noqa: E402

# Session on-hand lists: user input, not culinary data.
SESSION = {"broccoli": ["yogurt", "lemon", "garlic"],
           "cabbage": ["lemon"],
           "potato": ["dill", "olive_oil"]}
P = M.pretty


def key(c, ing: str, have: list[str]) -> list[str]:
    m = M.build(c, ing, have)
    st = m["states"]
    out = [f"## {ing} (on hand: {', '.join(P(h) for h in have) or 'nothing'})", ""]

    def line(q, rows):
        out.append(f"- **{q}** " + ("; ".join(rows) if rows else "none") + f" ({len(rows)})")

    line("S1 Preparations with a needed role that has no curated pairing:",
         [f"{s['label']} ({', '.join(n['role'] for n in M.of(m, s['component'], 'need') if n['coverage'] == 'not recorded')})"
          for s in st if any(n["coverage"] == "not recorded" for n in M.of(m, s["component"], "need"))])
    line("S2 Preparations with a curated pairing on hand:",
         [f"{s['label']} ({', '.join(sorted({P(p['ingredient']) for p in M.of(m, s['component'], 'pairing') if p['knowledge'] == 'curated' and p['availability'] == 'on hand'}))})"
          for s in st if any(p["knowledge"] == "curated" and p["availability"] == "on hand"
                             for p in M.of(m, s["component"], "pairing"))])
    line("S3 Preparations with an experimental pairing or a tasted idea:",
         [s["label"] for s in st
          if any(p["knowledge"] == "experimental" for p in M.of(m, s["component"], "pairing"))
          or any(i["testing"]["status"] == "tested" for i in M.of(m, s["component"], "idea"))])
    routes = []
    for s in st:
        for r in M.of(m, s["component"], "route_fit"):
            req = [e for e in M.of(m, s["component"], "route_element")
                   if e["route_id"] == r["route_id"] and e["optionality"] == "required"]
            if req and all(e["availability"] == "on hand" for e in req):
                routes.append(f"{s['label']}: {r['attrs']['name']}")
    line("S4 Routes with every required element on hand:", routes)
    out.append("")
    # understand probes: one fixed row per ingredient, the richest one
    s = max(st, key=lambda x: len(M.of(m, x["component"], ("pairing", "idea"))))
    comp = s["component"]
    needs = M.of(m, comp, "need")
    cov = [n["role"] for n in needs if n["coverage"] == "recorded"]
    unc = [n["role"] for n in needs if n["coverage"] != "recorded"]
    on = sorted({f"{P(p['ingredient'])} ({p['role']})" for p in M.of(m, comp, "pairing")
                 if p["knowledge"] == "curated" and p["availability"] == "on hand"})
    exp = [f"{P(p['ingredient'])} ({p['role']})" for p in M.of(m, comp, "pairing")
           if p["knowledge"] == "experimental"]
    tasted = [f"{P(i['ingredient'])}: {i['testing']['trials'][0]['verdict']}"
              for i in M.of(m, comp, "idea") if i["testing"]["status"] == "tested"]
    out += [f"Understand probes on **{s['label']}**:",
            f"- **U1** Needed roles with a curated pairing: {', '.join(cov) or 'none'}; without: {', '.join(unc) or 'none'}.",
            f"- **U2** Curated pairings on hand: {', '.join(on) or 'none'}.",
            f"- **U3** Hypotheses: experimental pairings {', '.join(exp) or 'none'}; "
            f"Scout ideas {len(M.of(m, comp, 'idea'))}; tasted {', '.join(tasted) or 'none'}.",
            f"- **U4** Knowledge gaps (not recorded): {'; '.join(M.gaps(m, comp)) or 'none'}. "
            "Not-on-hand items are not gaps.", ""]
    return out


def main() -> None:
    c = sqlite3.connect(":memory:")
    c.row_factory = sqlite3.Row
    loader.build(c)
    names = set(query.ingredients_list(c))
    lines = ["# Answer key (generated by evidence/answer_key.py)", ""]
    for ing, have in SESSION.items():
        assert set(have) <= names, (ing, set(have) - names)
        lines += key(c, ing, have)
    print("\n".join(lines))


if __name__ == "__main__":
    main()
