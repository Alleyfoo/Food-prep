"""Regenerate the generated parts of Culinary Operations R1.

Run from the repository root:

    py -3.11 docs/research/r1-culinary-operations/run.py

Writes, next to this file:
- operation-catalogue.md   the catalogue in operations.yaml, as a readable list
- applicability-tables.md  per ingredient part: every operation's status and why
- results.md               exploration statistics, top sequences, operation diversity

Takes about a minute. Deterministic: the same data gives the same files.
"""

from __future__ import annotations

import sys
from collections import Counter, defaultdict
from pathlib import Path

HERE = Path(__file__).parent
sys.path.insert(0, str(HERE.parents[2] / "src"))

from foodprep import operations as o  # noqa: E402

INGREDIENTS = ["broccoli", "carrot", "courgette", "tomato", "avocado"]
CATEGORY_ORDER = ["geometry", "separation", "extraction", "mechanical", "thermal", "chemical"]


def esc(x) -> str:
    return str(x).replace("|", "/").replace("\n", " ")


def catalogue_md(cat: o.Catalogue) -> str:
    out = ["# Operation catalogue",
           "",
           "Generated from `src/foodprep/data/operations.yaml` by `run.py`; edit the YAML, "
           "not this file. Source ids are explained in `sources.md`.",
           ""]
    by_cat = defaultdict(list)
    for k, op in cat.operations.items():
        by_cat[op["categories"][0]].append((k, op))
    total = len(cat.operations)
    gen = sum(1 for op in cat.operations.values() if op.get("generator", True))
    out.append(f"{total} operations; {gen} used by the sequence generator. "
               "Categories are not exclusive: an operation lists every mechanism family it "
               "belongs to, and is filed here under its first.")
    out.append("")
    for c in CATEGORY_ORDER:
        out += [f"## {c.capitalize()}", ""]
        for k, op in by_cat[c]:
            head = f"### {op['fr']} — {op['en']} (`{k}`)"
            out += [head, ""]
            rows = []
            if op.get("aliases"):
                rows.append(("Aliases", ", ".join(op["aliases"])))
            rows.append(("Categories", ", ".join(op["categories"])))
            if op.get("technique"):
                rows.append(("Ontology technique", f"`{op['technique']}`"))
            if op.get("preparation"):
                rows.append(("Produces preparation", f"`{op['preparation']}`"))
            req = op.get("requires") or {}
            if req:
                rows.append(("Requires", "; ".join(
                    f"{key} {v[0] if isinstance(v, list) else v} ({v[1] if isinstance(v, list) else ''})"
                    for key, v in req.items())))
            for rule in op.get("conditional") or []:
                rows.append(("Conditional", rule["note"]))
            for rule in op.get("unsafe_when") or []:
                rows.append(("Unsafe when", rule["note"]))
            for f, label in (("adds", "Adds"), ("equipment", "Equipment")):
                if op.get(f):
                    rows.append((label, ", ".join(op[f])))
            if op.get("effort"):
                rows.append(("Effort", str(op["effort"])))
            for f, label in (("parameters", "Parameters"), ("changes", "Property changes"),
                             ("applications", "Applications"), ("limitations", "Limitations"),
                             ("safety", "Safety")):
                if op.get(f):
                    rows.append((label, op[f]))
            if op.get("mechanisms"):
                rows.append(("Mechanisms", ", ".join(op["mechanisms"])))
            outs = op.get("outputs") or []
            if outs:
                rows.append(("Outputs", "; ".join(
                    f"{x.get('name', 'main')} ({x.get('kind', 'state')}"
                    + (f", from {x['from']}" if x.get("from") else "") + ")" for x in outs)))
            if op.get("established_on"):
                rows.append(("Documented on", ", ".join(op["established_on"])))
            rows.append(("Evidence", ", ".join(f"`{e}`" for e in op["evidence"])))
            rows.append(("Confidence", op["confidence"]))
            if op.get("generator", True) is False:
                rows.append(("Not generated", op["not_generated_because"]))
            if op.get("family_state"):
                rows.append(("Family generator state", f"`{op['generator_id']}`"))
            out += ["| Field | Value |", "| --- | --- |"]
            out += [f"| {a} | {esc(b)} |" for a, b in rows]
            out.append("")
    return "\n".join(out)


def applicability_md(cat: o.Catalogue) -> str:
    out = ["# Applicability tables",
           "",
           "Generated by `run.py` from operations.yaml and part_properties.yaml. For each "
           "starting part: every operation the generator may use, its status and the "
           "reasons. Statuses: applicable, conditional, inapplicable, unknown, unsafe.",
           ""]
    summary = ["| Ingredient part | applicable | conditional | inapplicable | unknown | unsafe |",
               "| --- | ---: | ---: | ---: | ---: | ---: |"]
    body = []
    for ing in INGREDIENTS:
        for m in o.start_materials(ing, cat=cat):
            counts = Counter()
            rows = []
            for k, op in cat.operations.items():
                if op.get("generator", True) is False:
                    continue
                a = o.assess(k, m, cat)
                counts[a.status] += 1
                outs = ""
                if a.status in o.TAKEN:
                    produced = o.apply(k, m, cat)
                    outs = "; ".join(
                        (f"{x.path[-1].output}: " if len(produced) > 1 else "")
                        + ", ".join(f"{c}" for c in o.changed(m, x) if c != "form")
                        for x in produced)
                rows.append((a.status, op["fr"], esc(a.explain()), esc(outs)))
            summary.append(f"| {m.name} | " + " | ".join(str(counts[s]) for s in o.STATUSES) + " |")
            body += [f"## {m.name}", ""]
            if m.edible == "no":
                body += [f"Not food: {m.edible_reason}", ""]
            body += ["| Status | Operation | Why | Changes (outputs) |",
                     "| --- | --- | --- | --- |"]
            order = {s: i for i, s in enumerate(o.STATUSES)}
            for st, name, why, outs in sorted(rows, key=lambda r: order[r[0]]):
                body.append(f"| {st} | {name} | {why} | {outs} |")
            body.append("")
    return "\n".join(out + summary + [""] + body)


def results_md(cat: o.Catalogue) -> str:
    out = ["# Results",
           "",
           "Generated by `run.py`. Depth 3. Sequences are hypotheses, not recipes; scores "
           "rank them for testing and are not a measure of taste.",
           "",
           "## Exploration",
           "",
           "| Ingredient | distinct materials | generated steps | merged as equivalent | "
           "no culinary function | ranked | pruned inapplicable | pruned unsafe | "
           "pruned unknown |",
           "| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |"]
    tops, diversity, unknown_all = {}, Counter(), Counter()
    fn_counts = Counter()
    for ing in INGREDIENTS:
        rs, ex = o.ranked(ing, cat=cat)
        s = ex.stats
        nofunc = sum(1 for r in ex.results if not o.useful_functions(r.material, cat))
        out.append(f"| {ing} | {len(ex.results)} | {s['generated']} | "
                   f"{s['merged: equivalent material']} | {nofunc} | {len(rs)} | "
                   f"{s['pruned: inapplicable']} | {s['pruned: unsafe']} | {s['pruned: unknown']} |")
        tops[ing] = o.diverse(rs, 8)
        unknown_all.update(ex.unknown_props)
        seen_sets = defaultdict(set)
        for x in rs:
            for st in x.result.path:
                seen_sets[st.operation].add(frozenset(x.functions))
            fn_counts.update(x.functions)
        for op, sets in seen_sets.items():
            diversity[op] += len(sets)
    out += ["", "## Top sequences per ingredient", "",
            "At most one per (part, fraction, main function, last operation), and a fair "
            "share per part (`operations.diverse`).", ""]
    for ing, xs in tops.items():
        out += [f"### {ing}", "", "| Score | Material | Sequence | Functions | Evidence |",
                "| ---: | --- | --- | --- | --- |"]
        for x in xs:
            m = x.result.material
            out.append(f"| {x.score:.2f} | {esc(m.name)} | {esc(o.describe_path(m))} | "
                       f"{', '.join(x.functions)} | {x.evidence} |")
        out.append("")
    out += ["## Operations by diversity of useful materials", "",
            "Number of distinct function sets among ranked sequences that use the operation, "
            "summed over the five ingredients.", "",
            "| Operation | distinct function sets |", "| --- | ---: |"]
    for op, n in diversity.most_common(20):
        out.append(f"| {cat.operations[op]['fr']} (`{op}`) | {n} |")
    out += ["", "## Functions among ranked sequences", "", "| Function | sequences |",
            "| --- | ---: |"]
    for f, n in fn_counts.most_common():
        out.append(f"| {f} | {n} |")
    out += ["", "## Properties that blocked a step as unknown", ""]
    if unknown_all:
        out += [f"- {k}: {n}" for k, n in unknown_all.most_common()]
    else:
        out.append("None: every property an operation asked about was stated for these "
                   "materials (see evaluation.md on what that does and does not show).")
    return "\n".join(out) + "\n"


def main() -> int:
    cat = o.load()
    (HERE / "operation-catalogue.md").write_text(catalogue_md(cat), encoding="utf-8")
    (HERE / "applicability-tables.md").write_text(applicability_md(cat), encoding="utf-8")
    (HERE / "results.md").write_text(results_md(cat), encoding="utf-8")
    print("wrote operation-catalogue.md, applicability-tables.md, results.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
