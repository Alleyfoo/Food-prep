"""R3 data adapter: one ingredient's knowledge as flat records + typed relations.

Every layout in this prototype reads ONLY from `build_model`, so the three
layouts show identical data. Nothing here ranks, scores or infers: it reads
the existing query layer and SQL tables and labels each record with its
*epistemic status* - what kind of statement it is.

Status vocabulary (the one thing R3 adds; it is a label, not a judgement):

    curated      hand-entered knowledge (transformation, needed role, pairing,
                 flavour route). Carries the record's own confidence.
    evidence     a cited source or corpus count that backs a curated record.
    hypothesis   generated by Scout's analogy rules; not a recommendation.
    tested       a tasting trial was recorded for it (with its verdict).
    on_hand      derived from what the user typed as available.
    not_recorded nothing is written for this cell. Not the same as "no".
"""
from __future__ import annotations

import sqlite3
from typing import Any

from foodprep import query

STATUSES = ("curated", "evidence", "hypothesis", "tested", "on_hand",
            "not_recorded")


def pretty(name: str | None) -> str:
    return (name or "").replace("_component", "").replace("_base", " base") \
        .replace("_", " ").strip()


def _sources(conn, transformation_id: int) -> list[dict]:
    return [dict(r) for r in conn.execute(
        """SELECT s.title, s.source_type, e.claim_scope
           FROM transformation_evidence e
           JOIN evidence_sources s USING (source_id)
           WHERE e.transformation_id = ? ORDER BY s.title""",
        (transformation_id,))]


def _pairings(conn, transformation_id: int) -> list[dict]:
    """All pairings for the step, experimental ones included and labelled."""
    rows = conn.execute(
        """SELECT p.pairing_id, i.canonical_name AS filler, r.role_name AS role,
                  p.confidence, p.application, p.availability_class,
                  p.common_context, p.corpus_cooccurrence_count AS corpus,
                  (SELECT COUNT(*) FROM pairing_evidence pe
                    WHERE pe.pairing_id = p.pairing_id) AS sources
           FROM pairings p
           JOIN ingredients i USING (ingredient_id)
           JOIN roles r USING (role_id)
           WHERE p.works_best_with_transformation_id = ?
           ORDER BY r.role_name, i.canonical_name""", (transformation_id,))
    return [dict(r) for r in rows]


def build_model(conn: sqlite3.Connection, ingredient: str,
                have: list[str] | None = None) -> dict[str, Any]:
    """{'ingredient', 'have', 'states': [...], 'relations': [...], 'roles': [...]}.

    states: one record per prepared ingredient, in the query layer's own order.
    relations: (source, kind, target, status, attrs) rows, the graph as a table.
    """
    have_set = {h for h in (have or []) if h}
    states: list[dict] = []
    relations: list[dict] = []
    role_order: list[str] = []

    def rel(src, kind, tgt, status, **attrs):
        relations.append({"source": src, "kind": kind, "target": tgt,
                          "status": status, **attrs})

    for rank, card in enumerate(query.all_branch_cards(conn, ingredient), 1):
        comp = card["component"]
        tid = card["transformation_id"]
        inp = conn.execute(
            """SELECT c.name FROM transformations t
               LEFT JOIN components c ON c.component_id = t.input_component_id
               WHERE t.transformation_id = ?""", (tid,)).fetchone()[0]
        routes = query.flavour_routes_for_component(conn, comp, sorted(have_set))
        hyps = query.generate_scout_hypotheses(conn, comp)
        pairs = _pairings(conn, tid)
        srcs = _sources(conn, tid)
        uses = query.dish_contexts_for_component(conn, comp)
        profile = query.component_state_profile(conn, comp)
        missing = card["missing"]

        roles = {}
        for m in missing:
            role = m["role_name"]
            if role not in role_order:
                role_order.append(role)
            fillers = [p for p in pairs if p["role"] == role]
            cook = [p for p in fillers if p["confidence"] != "experimental"]
            roles[role] = {
                "priority": m["priority"], "note": m["note"],
                "fillers": fillers,
                "on_hand": [p["filler"] for p in cook if p["filler"] in have_set],
                "status": ("on_hand" if any(p["filler"] in have_set for p in cook)
                           else "curated" if cook else "not_recorded"),
            }

        trials = [t for h in hyps for t in (h.get("trials") or [])]
        states.append({
            "rank": rank, "component": comp, "label": pretty(comp),
            "technique": card["technique"],
            "from": pretty(inp) if inp else f"raw {pretty(ingredient)}",
            "transformation_id": tid,
            "confidence": card["confidence"],
            "flavour_shift": card["flavour_shift"],
            "texture_shift": card["texture_shift"],
            "keeps_well": card["keeps_well"],
            "freezes_well": bool(card["freezes_well"]),
            "batch_prep_value": card["batch_prep_value"],
            "risks": [pretty(r) for r in card["risks"]],
            "tags": [t["value"] for t in card["tags"] if t["family"] != "state"],
            "roles": roles,
            "routes": routes,
            "hypotheses": hyps,
            "trials": trials,
            "sources": srcs,
            "uses": uses,
            "profile": profile,
        })

        # --- relations, the same facts as edges -------------------------
        rel(ingredient, "becomes", comp, "curated", via=card["technique"],
            confidence=card["confidence"])
        if inp:
            rel(inp, "becomes", comp, "curated", via=card["technique"],
                confidence=card["confidence"])
        for s in srcs:
            rel(comp, "backed by", s["title"], "evidence", scope=s["claim_scope"])
        for role, r in roles.items():
            rel(comp, "needs", role, "curated", priority=r["priority"],
                filled=bool(r["fillers"]))
            for p in r["fillers"]:
                st = ("hypothesis" if p["confidence"] == "experimental"
                      else "on_hand" if p["filler"] in have_set else "curated")
                rel(role, "filled by", p["filler"], st, state=comp,
                    confidence=p["confidence"], application=p["application"],
                    sources=p["sources"], corpus=p["corpus"])
        for rt in routes:
            rel(comp, "route", rt["route_id"], "curated", name=rt["name"],
                attestation=rt["attestation"], fit=rt.get("fit_reason"))
            for e in rt["elements"]:
                rel(rt["route_id"], "uses", e["ingredient"],
                    "on_hand" if e["ingredient"] in have_set else "curated",
                    optionality=e["optionality"], contribution=e["contribution"])
        for h in hyps:
            tried = h.get("trials") or []
            rel(comp, "idea", h["candidate"],
                "tested" if tried else "hypothesis",
                strength=h["inference_strength"],
                novelty=(h.get("novelty") or {}).get("class"),
                verdict=tried[0]["verdict"] if tried else None,
                analogy=h["analogy_id"], replaces=h["source"])
        for u in uses:
            rel(comp, "used in", u, "curated")

    return {"ingredient": ingredient, "have": sorted(have_set),
            "states": states, "relations": relations, "roles": role_order}


def state_gaps(s: dict) -> list[str]:
    """What is NOT recorded for a state, said plainly (never 'none needed')."""
    out = []
    if not s["routes"]:
        out.append("no flavour route")
    empty = [r for r, v in s["roles"].items() if not v["fillers"]]
    if empty:
        out.append("no pairing for " + ", ".join(empty))
    if not s["roles"] and not s["routes"]:
        out.append("no needed roles")
    if not s["sources"]:
        out.append("no cited source")
    if not s["hypotheses"]:
        out.append("no Scout idea")
    if not s["profile"]:
        out.append("no sensory profile")
    return out
